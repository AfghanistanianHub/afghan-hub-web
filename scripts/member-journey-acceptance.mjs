    assert.equal(messageNotification.data.actor_id, a.userId);
    assert.equal(messageNotification.data.recipient_id, b.userId);

    const leakedMessageNotification = await a.supabase
      .from("notifications")
      .select("id")
      .eq("id", messageNotification.data.id)
      .maybeSingle();
    assert.ifError(leakedMessageNotification.error);
    assert.equal(leakedMessageNotification.data, null, "Sender can read recipient-only message notification");

    const unreadBefore = await b.supabase.rpc("get_unread_message_counts");
