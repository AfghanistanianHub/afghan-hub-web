    assert.equal(acceptedNotification.data.actor_id, b.userId);
    assert.equal(acceptedNotification.data.recipient_id, a.userId);
    console.log("PASS recipient-only response and accepted-state notification");

    const direct = await a.supabase.rpc("start_direct_conversation", {
      target_member_id: b.userId,
    });
    assert.ifError(direct.error);
    const conversationId = direct.data;
    assert.ok(conversationId, "Direct conversation creation returned no id");

