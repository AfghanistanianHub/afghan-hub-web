import assert from "node:assert/strict";
import { writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { createClient } from "@supabase/supabase-js";

const PRODUCTION_PROJECT_REF = "yussznmwjsvfvpabmwdc";
const PRODUCTION_ACK = "I_UNDERSTAND_THESE_ARE_DISPOSABLE_TEST_ACCOUNTS";
const WRITE_ACK = "I_UNDERSTAND_THIS_CREATES_DISPOSABLE_PRODUCTION_FIXTURES";
const CLEANUP_ACK = "I_WILL_CLEAN_UP_EXACT_CAPTURED_FIXTURE_IDS";

const required = [
  "AUTH_ACCEPTANCE_SUPABASE_URL",
  "AUTH_ACCEPTANCE_PUBLISHABLE_KEY",
  "AUTH_ACCEPTANCE_MEMBER_A_EMAIL",
  "AUTH_ACCEPTANCE_MEMBER_A_PASSWORD",
  "AUTH_ACCEPTANCE_MEMBER_B_EMAIL",
  "AUTH_ACCEPTANCE_MEMBER_B_PASSWORD",
];
for (const name of required) {
  assert.ok(process.env[name]?.trim(), `Missing required environment variable: ${name}`);
}

const mode = process.env.JOURNEY_ACCEPTANCE_MODE?.trim() || "plan";
assert.ok(["plan", "write"].includes(mode), "JOURNEY_ACCEPTANCE_MODE must be plan or write");

const supabaseUrl = process.env.AUTH_ACCEPTANCE_SUPABASE_URL.trim().replace(/\/+$/, "");
const publishableKey = process.env.AUTH_ACCEPTANCE_PUBLISHABLE_KEY.trim();
const target = new URL(supabaseUrl);
assert.equal(target.protocol, "https:", "Journey acceptance requires an HTTPS Supabase URL");
const isProduction = target.hostname.includes(PRODUCTION_PROJECT_REF);

if (isProduction) {
  assert.equal(
    process.env.AUTH_ACCEPTANCE_ALLOW_PRODUCTION,
    PRODUCTION_ACK,
    "Refusing production journey without the disposable-account acknowledgement",
  );
}
if (mode === "write") {
  assert.equal(
    process.env.JOURNEY_ACCEPTANCE_ALLOW_WRITES,
    WRITE_ACK,
    "Refusing write journey without the explicit write acknowledgement",
  );
  if (isProduction) {
    assert.equal(
      process.env.JOURNEY_ACCEPTANCE_CLEANUP_ACK,
      CLEANUP_ACK,
      "Refusing production writes without explicit cleanup acknowledgement",
    );
  }
}

const configured = [
  {
    label: "Member A",
    email: process.env.AUTH_ACCEPTANCE_MEMBER_A_EMAIL.trim(),
    password: process.env.AUTH_ACCEPTANCE_MEMBER_A_PASSWORD,
  },
  {
    label: "Member B",
    email: process.env.AUTH_ACCEPTANCE_MEMBER_B_EMAIL.trim(),
    password: process.env.AUTH_ACCEPTANCE_MEMBER_B_PASSWORD,
  },
];
assert.notEqual(
  configured[0].email.toLowerCase(),
  configured[1].email.toLowerCase(),
  "Member A and Member B must be distinct disposable accounts",
);

function client() {
  return createClient(supabaseUrl, publishableKey, {
    auth: { persistSession: false, autoRefreshToken: false, detectSessionInUrl: false },
  });
}

async function signIn(persona) {
  const supabase = client();
  const result = await supabase.auth.signInWithPassword({
    email: persona.email,
    password: persona.password,
  });
  assert.ifError(result.error);
  assert.ok(result.data.user?.id, `${persona.label} sign-in returned no user id`);
  assert.ok(result.data.user?.email_confirmed_at, `${persona.label} is not email-confirmed`);

  const access = await supabase.rpc("get_my_access_context");
  assert.ifError(access.error);
  const state = access.data?.[0] ?? null;
  assert.ok(state, `${persona.label} access context is missing`);
  assert.equal(state.role, "member", `${persona.label} must be an ordinary member persona`);
  assert.equal(state.onboarding_completed, true, `${persona.label} has not completed onboarding`);

  return { ...persona, supabase, userId: result.data.user.id };
}

async function signOut(persona) {
  if (!persona?.supabase) return;
  const result = await persona.supabase.auth.signOut({ scope: "local" });
  assert.ifError(result.error);
}

async function findPairConnections(a, b) {
  const result = await a.supabase
    .from("connections")
    .select("id,status,requester_id,recipient_id")
    .or(
      `and(requester_id.eq.${a.userId},recipient_id.eq.${b.userId}),and(requester_id.eq.${b.userId},recipient_id.eq.${a.userId})`,
    );
  assert.ifError(result.error);
  return result.data ?? [];
}

function cleanupSql(ids) {
  return `-- Generated by scripts/member-journey-acceptance.mjs\n-- Review exact IDs before execution. This is destructive cleanup for disposable acceptance fixtures only.\nbegin;\n\ndo $$\ndeclare\n  connection_matches integer;\n  conversation_matches integer;\n  message_matches integer;\nbegin\n  select count(*) into connection_matches\n  from public.connections\n  where id = '${ids.connectionId}'::uuid\n    and requester_id = '${ids.memberAId}'::uuid\n    and recipient_id = '${ids.memberBId}'::uuid;\n\n  select count(*) into conversation_matches\n  from public.conversations\n  where id = '${ids.conversationId}'::uuid\n    and created_by = '${ids.memberAId}'::uuid;\n\n  select count(*) into message_matches\n  from public.messages\n  where id = '${ids.messageId}'::uuid\n    and conversation_id = '${ids.conversationId}'::uuid\n    and sender_id = '${ids.memberAId}'::uuid;\n\n  if connection_matches <> 1 or conversation_matches <> 1 or message_matches <> 1 then\n    raise exception 'Fixture identity assertion failed; refusing cleanup';\n  end if;\nend $$;\n\ndelete from public.notifications\nwhere connection_id = '${ids.connectionId}'::uuid\n   or message_id = '${ids.messageId}'::uuid\n   or conversation_id = '${ids.conversationId}'::uuid;\n\ndelete from public.messages\nwhere id = '${ids.messageId}'::uuid\n  and conversation_id = '${ids.conversationId}'::uuid\n  and sender_id = '${ids.memberAId}'::uuid;\n\ndelete from public.conversation_members\nwhere conversation_id = '${ids.conversationId}'::uuid\n  and profile_id in ('${ids.memberAId}'::uuid, '${ids.memberBId}'::uuid);\n\ndelete from public.conversations\nwhere id = '${ids.conversationId}'::uuid\n  and created_by = '${ids.memberAId}'::uuid;\n\ndelete from public.connections\nwhere id = '${ids.connectionId}'::uuid\n  and requester_id = '${ids.memberAId}'::uuid\n  and recipient_id = '${ids.memberBId}'::uuid;\n\ncommit;\n`;
}

let a;
